"""Each project case study publishes parsable schema.org data about itself.

The data is generated by scripts/site.lua from the page's own title, description
and social image, so it can never drift from what the page says. The shared
Person schema in partials/head.html stays on every page and is checked as a guard.
"""

import json
import re

import test_links as checks

SITE = "https://exios66.github.io/resume/"
PROJECTS = sorted(p.stem for p in (checks.ROOT / "projects").glob("*.qmd") if p.stem != "index")
SCRIPT = re.compile(r'<script type="application/ld\+json">(.*?)</script>', re.S)
H1 = re.compile(r'<h1 class="page-title"[^>]*>(.*?)</h1>', re.S)
TAG = re.compile(r"<[^>]+>")


def plain(fragment):
    """Return visible text with Pandoc's typographic apostrophes folded back to ASCII."""
    return TAG.sub("", fragment).replace("\u2019", "'").replace("\u2018", "'").strip()


def case_study(slug):
    """Read the built case study and return its parsed JSON-LD blocks."""
    text = (checks.DOCS / "projects" / f"{slug}.html").read_text(encoding="utf-8")
    blocks = SCRIPT.findall(text)
    assert blocks, f"{slug}: no JSON-LD blocks"
    return text, [json.loads(block) for block in blocks]


def test_every_case_study_has_parsable_creative_work_data():
    for slug in PROJECTS:
        text, blocks = case_study(slug)
        works = [block for block in blocks if block.get("@type") == "CreativeWork"]
        assert len(works) == 1, f"{slug}: expected one CreativeWork block, got {len(works)}"
        work = works[0]
        assert work["@context"] == "https://schema.org"
        assert work["name"] == plain(H1.search(text).group(1)), slug
        assert work["description"], f"{slug}: empty description"
        assert work["url"] == f"{SITE}projects/{slug}.html"
        assert work["author"] == {"@type": "Person", "name": "Jack J. Burleson", "url": SITE}
        assert work["isPartOf"] == {"@type": "WebSite", "name": "Jack J. Burleson", "url": SITE}
        assert work["image"].startswith(SITE) and work["image"].endswith(".png"), slug
        # A description must never be able to close the surrounding script element.
        assert "<" not in json.dumps(work, ensure_ascii=False), slug


def test_the_shared_person_schema_stays_on_every_page():
    for page in checks.site_files(include_libs=False):
        blocks = SCRIPT.findall(page.read_text(encoding="utf-8"))
        parsed = [json.loads(block) for block in blocks]
        assert any(block.get("@type") == "Person" for block in parsed), checks.rel(page)


def test_reports_and_appendices_keep_only_the_person_schema():
    nested = [p for p in (checks.DOCS / "projects").rglob("*.html") if p.parent.name != "projects"]
    assert len(nested) >= 9
    for page in nested:
        blocks = [json.loads(block) for block in SCRIPT.findall(page.read_text(encoding="utf-8"))]
        assert not any(block.get("@type") == "CreativeWork" for block in blocks), checks.rel(page)
